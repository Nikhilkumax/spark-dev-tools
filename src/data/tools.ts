export const tools: Tool[] = Object.entries(groups).flatMap(([category, items]) =>
  items.map(([name, icon, description]) => ({
    name,
    slug: slugify(name),
    description,
    icon,
    category,
  }))
);

export const categories: string[] = Object.keys(groups);

export function categorySlug(name: string): string {
  return slugify(name);
}

export function categoryFromSlug(slug: string): string | undefined {
  return categories.find((c) => categorySlug(c) === slug);
}

export function findTool(catSlug: string, toolSlug: string) {
  const categoryName = categoryFromSlug(catSlug);
  if (!categoryName) return null;
  const tool = tools.find((t) => t.category === categoryName && t.slug === toolSlug);
  if (!tool) return null;
  return { tool, categoryName };
}
